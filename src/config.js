/* ---- виды эффектов -------------------------------------------------
   mul  : val(n) = V0 * m^n
   mul1 : val(0) = 0, val(n) = V0 * m^(n-1)   (эффект появляется с 1 уровня)
   add  : val(n) = V0 + step*n, с необязательным потолком max
--------------------------------------------------------------------- */
const mul  = (V0, m)          => ({ kind: 'mul',  V0, m });
const mul1 = (V0, m)          => ({ kind: 'mul1', V0, m });
const add  = (V0, step, max)  => ({ kind: 'add',  V0, step, max });

